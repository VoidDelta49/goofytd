// Seeded PRNG for the simulation. Math.random is unseeded and differs per
// run; the sim must replay identically from a seed.

/** mulberry32: tiny, fast, good enough for gameplay jitter. Returns () => [0, 1). */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function rng() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
